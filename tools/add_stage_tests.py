def est_lines(text, width):
    """Оценка числа отрисованных строк (калибровка по уже принятым блокам 01-06)."""
    per = max(20.0, (width - 40) / 8.6)
    total = 0
    for ln in text.split("\n"):
        plain = re.sub(r"[*`#>|-]", "", ln)
        total += max(1, math.ceil(len(plain) / per))
    return total


def x_overlap(a, b):
    return a["x"] < b["x"] + b["width"] and b["x"] < a["x"] + a["width"]


def contains(group, n):
    return (n["x"] >= group["x"] and n["y"] >= group["y"]
            and n["x"] + n["width"] <= group["x"] + group["width"]
            and n["y"] + n["height"] <= group["y"] + group["height"])


