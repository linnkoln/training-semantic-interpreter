# 5) снятие налезаний: узлы ниже сдвигаются вниз внутри своей колонки
nodes = [n for n in data["nodes"] if n.get("type") == "text"]
moved = []
for _ in range(200):
    changed = False
    for i, a in enumerate(nodes):
        for b in nodes[i + 1:]:
            if not x_overlap(a, b):
                continue
            upper, lower = (a, b) if a["y"] <= b["y"] else (b, a)
            need_y = upper["y"] + upper["height"] + GAP
            if lower["y"] < need_y:
                delta = need_y - lower["y"]
                lower["y"] = need_y
                moved.append((lower["id"], delta))
                changed = True
    if not changed:
        break

